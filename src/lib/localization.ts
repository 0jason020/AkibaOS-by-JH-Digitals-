export function isAppLanguage(value: string): value is AppLanguage {
  return (APP_LANGUAGES as readonly string[]).includes(value)
}

export function translate(language: string, text: string) {
  if (language === 'English') return text
  return catalogs[language as Exclude<AppLanguage, 'English'>]?.[text] ?? text
}

export function languageTag(language: string) {
  switch (language) {
    case 'Kinyarwanda': return 'rw'
    case 'Français': return 'fr'
    case 'Kiswahili': return 'sw'
    default: return 'en'
  }
}
